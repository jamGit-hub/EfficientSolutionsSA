/* ── State ────────────────────────────────────────────────── */
let currentLang = localStorage.getItem('es_lang') || 'en';

/* ── DOM Helpers ──────────────────────────────────────────── */
const $ = (s, ctx = document) => ctx.querySelector(s);
const $$ = (s, ctx = document) => [...ctx.querySelectorAll(s)];

/* ── Apply Language ───────────────────────────────────────── */
function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('es_lang', lang);

  document.documentElement.lang = lang;
  document.documentElement.dir  = lang === 'ar' ? 'rtl' : 'ltr';

  const t = translations[lang];
  if (!t) return;

  /* Translate elements with data-i18n attribute */
  $$('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) {
      el.textContent = t[key];
    }
  });

  /* Update lang button states (desktop + mobile toggles) */
  $$('.lang-btn').forEach(btn => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', String(isActive));
  });
}

/* ── Sticky Nav ───────────────────────────────────────────── */
function initNav() {
  const navbar = $('#navbar');
  if (!navbar) return;

  const onScroll = () => {
    navbar.classList.toggle('scrolled', window.scrollY > 40);
  };

  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  /* Highlight active page link */
  const current = window.location.pathname.split('/').pop() || 'index.html';
  $$('.nav-links a').forEach(a => {
    if (a.getAttribute('href') === current) a.classList.add('active');
  });
}

/* ── Mobile Menu ──────────────────────────────────────────── */
function initMobileMenu() {
  const hamburger = $('.hamburger');
  const mobileNav = $('.mobile-nav');
  if (!hamburger || !mobileNav) return;

  const closeMenu = () => {
    hamburger.classList.remove('open');
    mobileNav.classList.remove('open');
    hamburger.setAttribute('aria-expanded', 'false');
  };

  hamburger.addEventListener('click', () => {
    const open = hamburger.classList.toggle('open');
    mobileNav.classList.toggle('open', open);
    hamburger.setAttribute('aria-expanded', String(open));
  });

  /* Close when a link is clicked */
  $$('.mobile-nav a').forEach(a => {
    a.addEventListener('click', closeMenu);
  });

  /* Close automatically when the window is stretched back to desktop width
     (matches the .nav-links/.hamburger breakpoint in style.css) */
  const desktopQuery = window.matchMedia('(min-width: 1025px)');
  desktopQuery.addEventListener('change', (e) => {
    if (e.matches) closeMenu();
  });
}

/* ── Language Buttons ─────────────────────────────────────── */
/* Delegated on document so it works for buttons that are injected
   later (the shared navbar is fetched from navbar.html after load). */
function initLanguageToggle() {
  document.addEventListener('click', e => {
    const btn = e.target.closest('.lang-btn');
    if (!btn || !btn.dataset.lang || btn.dataset.lang === currentLang) return;
    applyLanguage(btn.dataset.lang);
  });
}

/* ── Shared Navbar ────────────────────────────────────────── */
/* Every page has <div id="navbar-container"></div>; the markup lives in
   navbar.html. Everything that touches the navbar (sticky state, mobile
   menu, dropdowns, translation of its labels) must run AFTER injection. */
async function loadNavbar() {
  const container = document.getElementById('navbar-container');
  if (!container) return;
  try {
    const res = await fetch('navbar.html');
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const doc = new DOMParser().parseFromString(await res.text(), 'text/html');
    doc.querySelectorAll('script').forEach(s => s.remove());
    container.innerHTML = doc.body.innerHTML;
  } catch (err) {
    console.error('Navbar failed to load:', err);
    return;
  }
  initNav();
  initMobileMenu();
  initDropdowns();
  applyLanguage(currentLang);   // translate navbar labels + set active EN/AR button
}

/* ── Reveal on Scroll ─────────────────────────────────────── */
function initReveal() {
  const targets = $$('.reveal, .reveal-left, .reveal-right');
  if (!targets.length) return;

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

  targets.forEach(el => observer.observe(el));
}

/* ── Stagger Children ─────────────────────────────────────── */
function initStagger() {
  $$('.stagger').forEach(parent => {
    $$(':scope > *', parent).forEach((child, i) => {
      child.style.setProperty('--i', i);
    });
  });
}

